import { chmodSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { describe, expect, it } from 'vitest';
import { BatchGenerator } from '../src/components/BatchGenerator.js';

const TWO_JOB_QUEUE = [
  { id: '1', inputName: 'benzene.gjf', outputName: 'benzene.log', gjfText: 'benzene input' },
  { id: '2', inputName: 'water.gjf', outputName: 'water.log', gjfText: 'water input' },
];

function makeShBatch(queue, linuxCmd = 'g16') {
  const batch = Object.create(BatchGenerator.prototype);
  batch.format = 'sh';
  batch.linuxCmd = linuxCmd;
  batch.queue = queue;
  return batch;
}

const GOLDEN_TWO_JOB_SCRIPT = `#!/bin/bash
# Gaussian Batch Job Script
# Generated by GaussianHelper

# Termination check only: after each job this script classifies the output
# by Gaussian termination marker ("Normal termination of Gaussian" =
# terminated normally, "Error termination" = failed, neither = unknown).
# It is NOT a substitute for the GaussianHelper Workbench validation
# gates; open the outputs in the Workbench for full validation.
# Gaussian exits 0 even on "Error termination", so the process exit code
# is never treated as proof of success.

# Check if the Gaussian command exists in path
GAUSSIAN_CMD='g16'
if ! command -v "$GAUSSIAN_CMD" &> /dev/null; then
    echo "Error: $GAUSSIAN_CMD could not be found. Please check your execution command or environment."
    exit 1
fi

echo "============================================="
echo "Starting Gaussian batch execution..."
echo "NOTE: Results below are a termination check only, NOT a substitute"
echo "      for the GaussianHelper Workbench validation gates."
echo "============================================="

printf '[Job 1/2] Running %s < %s > %s\\n' "$GAUSSIAN_CMD" 'benzene.gjf' 'benzene.log'
"$GAUSSIAN_CMD" < 'benzene.gjf' > 'benzene.log'
job_status=$?
if [ "$job_status" -ne 0 ]; then
    echo "❌ Job 1 execution error: Gaussian exited with status $job_status (see 'benzene.log'). Continuing batch..."
elif grep -q "^ Normal termination of Gaussian" 'benzene.log'; then
    echo "✓ Job 1 terminated normally (termination check only, not a Workbench gate evaluation)"
elif grep -q "Error termination" 'benzene.log'; then
    echo "❌ Job 1 Gaussian error termination (see 'benzene.log'). Continuing batch..."
else
    echo "⚠ Job 1 has no termination marker (see 'benzene.log'). Status unknown; treat as unverified. Continuing batch..."
fi

printf '[Job 2/2] Running %s < %s > %s\\n' "$GAUSSIAN_CMD" 'water.gjf' 'water.log'
"$GAUSSIAN_CMD" < 'water.gjf' > 'water.log'
job_status=$?
if [ "$job_status" -ne 0 ]; then
    echo "❌ Job 2 execution error: Gaussian exited with status $job_status (see 'water.log'). Continuing batch..."
elif grep -q "^ Normal termination of Gaussian" 'water.log'; then
    echo "✓ Job 2 terminated normally (termination check only, not a Workbench gate evaluation)"
elif grep -q "Error termination" 'water.log'; then
    echo "❌ Job 2 Gaussian error termination (see 'water.log'). Continuing batch..."
else
    echo "⚠ Job 2 has no termination marker (see 'water.log'). Status unknown; treat as unverified. Continuing batch..."
fi

echo "============================================="
echo "Gaussian batch run finished."
echo "============================================="`;

// A stand-in for Gaussian: Gaussian exits 0 on "Error termination", so the
// fake does too in every case except the explicit execution-error sentinel.
const FAKE_GAUSSIAN = `#!/bin/bash
input=$(cat)
case "$input" in
  *ERROR_TERMINATION*) printf ' Error termination via Lnk1e in l502.exe\\n' ;;
  *NORMAL_TERMINATION*) printf ' Normal termination of Gaussian 16 at Fri Nov  6 18:00:00 2026.\\n' ;;
  *EXECUTION_ERROR*) printf 'wrapper crashed\\n' >&2; exit 3 ;;
  *NO_MARKER*) printf 'Some output with no termination line\\n' ;;
esac
exit 0
`;

function runGeneratedScript(queue) {
  const dir = mkdtempSync(join(tmpdir(), 'gh-batch-termination-'));
  try {
    const binDir = join(dir, 'bin');
    mkdirSync(binDir);
    const fake = join(binDir, 'gaussian');
    writeFileSync(fake, FAKE_GAUSSIAN);
    chmodSync(fake, 0o755);

    for (const item of queue) {
      writeFileSync(join(dir, item.inputName), item.gjfText);
    }
    writeFileSync(join(dir, 'run.sh'), makeShBatch(queue, 'gaussian').generateScriptContent());

    const stdout = execFileSync('bash', ['run.sh'], {
      cwd: dir,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
      env: { ...process.env, PATH: `${binDir}:${process.env.PATH ?? ''}` },
    });

    const outputs = {};
    for (const item of queue) {
      outputs[item.outputName] = readFileSync(join(dir, item.outputName), 'utf8');
    }
    return { stdout, outputs };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe('Linux batch runner termination check (issue #3)', () => {
  it('generates the exact golden script for a two-job queue', () => {
    expect(makeShBatch(TWO_JOB_QUEUE).generateScriptContent()).toBe(GOLDEN_TWO_JOB_SCRIPT);
  });

  it('never decides success from the process exit code', () => {
    const script = makeShBatch(TWO_JOB_QUEUE).generateScriptContent();

    expect(script).not.toContain('$? -eq 0');
    expect(script).not.toContain('completed successfully');
    expect(script).toContain('job_status=$?');
    expect(script).toContain('if [ "$job_status" -ne 0 ]; then');
  });

  it('states in a comment and an echo that this is only a termination check', () => {
    const script = makeShBatch(TWO_JOB_QUEUE).generateScriptContent();

    expect(script).toContain('# It is NOT a substitute for the GaussianHelper Workbench validation');
    expect(script).toContain('echo "NOTE: Results below are a termination check only, NOT a substitute"');
    expect(script).toContain('echo "      for the GaussianHelper Workbench validation gates."');
  });

  it('reports Error termination as failed even though Gaussian exits 0', () => {
    const { stdout, outputs } = runGeneratedScript([
      { id: '1', inputName: 'fail.gjf', outputName: 'fail.log', gjfText: 'ERROR_TERMINATION' },
    ]);

    expect(stdout).toContain('❌ Job 1 Gaussian error termination (see \'fail.log\'). Continuing batch...');
    expect(stdout).not.toContain('✓ Job 1');
    expect(stdout).not.toContain('completed successfully');
    expect(outputs['fail.log']).toContain(' Error termination');
  });

  it('reports Normal termination of Gaussian as terminated normally', () => {
    const { stdout } = runGeneratedScript([
      { id: '1', inputName: 'ok.gjf', outputName: 'ok.log', gjfText: 'NORMAL_TERMINATION' },
    ]);

    expect(stdout).toContain('✓ Job 1 terminated normally (termination check only, not a Workbench gate evaluation)');
    expect(stdout).not.toContain('Gaussian error termination');
  });

  it('reports a missing termination marker as unknown instead of successful', () => {
    const { stdout } = runGeneratedScript([
      { id: '1', inputName: 'empty.gjf', outputName: 'empty.log', gjfText: 'NO_MARKER' },
    ]);

    expect(stdout).toContain('⚠ Job 1 has no termination marker (see \'empty.log\'). Status unknown; treat as unverified. Continuing batch...');
    expect(stdout).not.toContain('✓ Job 1');
  });

  it('reports a nonzero process exit as an execution error, distinct from a Gaussian error termination', () => {
    const { stdout } = runGeneratedScript([
      { id: '1', inputName: 'crash.gjf', outputName: 'crash.log', gjfText: 'EXECUTION_ERROR' },
      { id: '2', inputName: 'ok.gjf', outputName: 'ok.log', gjfText: 'NORMAL_TERMINATION' },
    ]);

    expect(stdout).toContain('❌ Job 1 execution error: Gaussian exited with status 3 (see \'crash.log\'). Continuing batch...');
    expect(stdout).not.toContain('Job 1 Gaussian error termination');
    // The batch still continues to the next job.
    expect(stdout).toContain('✓ Job 2 terminated normally');
  });
});
